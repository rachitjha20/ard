"""Managed data directory.

Files are addressed by internal keys such as ``originals/<id>.pdf``. Keys are
generated by ARD and never built from user-supplied names, and every key is
resolved with a containment check, so nothing can be read or written outside
the data directory.
"""

from __future__ import annotations

import hashlib
import os
import re
import stat
import time
from pathlib import Path
from typing import BinaryIO

from app.core.config.settings import DATA_AREAS, Settings
from app.models import new_id

_ID = re.compile(r"^[0-9a-f]{32}$")


class StorageError(Exception):
    pass


class UploadTooLarge(StorageError):
    pass


class Storage:
    def __init__(self, settings: Settings) -> None:
        self._settings = settings
        self.root = settings.data_dir

    def ensure(self) -> None:
        self.root.mkdir(parents=True, exist_ok=True)
        for area in DATA_AREAS:
            (self.root / area).mkdir(exist_ok=True)

    def resolve(self, key: str) -> Path:
        root = self.root.resolve()
        path = (root / key).resolve()
        if root != path and root not in path.parents:
            raise StorageError("Path escapes the ARD data directory.")
        return path

    @staticmethod
    def _require_id(value: str) -> str:
        if not _ID.match(value):
            raise StorageError("Invalid internal identifier.")
        return value

    # ---- keys -------------------------------------------------------------
    def original_key(self, document_id: str) -> str:
        return f"originals/{self._require_id(document_id)}.pdf"

    def version_key(self, document_id: str, version_id: str) -> str:
        return f"versions/{self._require_id(document_id)}/{self._require_id(version_id)}.pdf"

    def thumbnail_path(self, version_id: str, page: int, width: int) -> Path:
        return self.resolve(f"thumbnails/{self._require_id(version_id)}/{int(page)}_{int(width)}.png")

    def temp_path(self, suffix: str = ".tmp") -> Path:
        return self.resolve(f"temporary/{new_id()}{suffix}")

    # ---- uploads ----------------------------------------------------------
    def receive(self, stream: BinaryIO, max_bytes: int) -> tuple[Path, str, int]:
        """Stream an upload to a temporary file, hashing and size-checking as it goes."""
        target = self.temp_path(".upload")
        digest = hashlib.sha256()
        size = 0
        try:
            with open(target, "wb") as handle:
                while True:
                    block = stream.read(1 << 20)
                    if not block:
                        break
                    size += len(block)
                    if size > max_bytes:
                        raise UploadTooLarge(
                            f"The file is larger than the {max_bytes // (1024 * 1024)} MB import limit."
                        )
                    digest.update(block)
                    handle.write(block)
                handle.flush()
                os.fsync(handle.fileno())
        except BaseException:
            target.unlink(missing_ok=True)
            raise
        return target, digest.hexdigest(), size

    def commit_original(self, temp: Path, document_id: str) -> str:
        key = self.original_key(document_id)
        destination = self.resolve(key)
        os.replace(temp, destination)
        self.make_read_only(destination)
        return key

    @staticmethod
    def make_read_only(path: Path) -> None:
        """Stored originals and versions are immutable: drop write permission."""
        try:
            path.chmod(stat.S_IRUSR | stat.S_IRGRP)
        except OSError:
            pass

    def remove_quietly(self, path: Path | str) -> None:
        path = Path(path)
        try:
            resolved = path.resolve()
            root = self.root.resolve()
            if root in resolved.parents:
                resolved.unlink(missing_ok=True)
        except OSError:
            pass

    def cleanup_temporary(self, older_than_seconds: float = 0) -> int:
        """Remove leftover temporary and partial files. Never touches stored documents."""
        removed = 0
        cutoff = time.time() - older_than_seconds
        candidates = list((self.root / "temporary").glob("*"))
        for area in ("originals", "versions", "thumbnails"):
            candidates.extend((self.root / area).rglob("*.part"))
        for path in candidates:
            try:
                if path.is_file() and path.stat().st_mtime <= cutoff:
                    path.unlink()
                    removed += 1
            except OSError:
                continue
        return removed

    def usage(self) -> dict[str, int]:
        result = {}
        for area in DATA_AREAS:
            total = 0
            for path in (self.root / area).rglob("*"):
                try:
                    if path.is_file():
                        total += path.stat().st_size
                except OSError:
                    continue
            result[area] = total
        return result
